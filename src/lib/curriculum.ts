const ROWS: Record<Track, Row[]> = {
  scratch: SCRATCH,
  python: PYTHON,
  roblox: ROBLOX,
  unity: UNITY,
  tosel: TOSEL,
};

function build(track: Track): WeekPlan[] {
  return ROWS[track].map(([title, plan1, plan2, ai, star], i) => ({
    week: i + 1,
    phase: i < 12 ? '기본' : '심화',
    title,
    goal: plan1,
    plan2,
    ai,
    milestone: !!star,
  }));
}

export const CURRICULUM: Record<Track, WeekPlan[]> = {
  scratch: build('scratch'),
  python: build('python'),
  roblox: build('roblox'),
  unity: build('unity'),
  tosel: build('tosel'),
};

export const TRACK_LIST: TrackMeta[] = Object.values(TRACK_META);

export function weekPlan(track: Track, week: number): WeekPlan | undefined {
  return CURRICULUM[track].find((w) => w.week === week);
}

/** 기존 코딩 레벨로 트랙 기본값을 정합니다 (원장님이 언제든 바꿀 수 있음) */
export function defaultTrackFor(codingLevel: string | undefined): Track {
  switch (codingLevel) {
    case 'C2':
      return 'python';
    case 'C3':
      return 'roblox';
    case 'C4':
      return 'unity';
    default:
      return 'scratch';
  }
}

/** 문자열 트랙 값을 안전하게 Track 으로 (DB에서 온 값 대비) */
export function asTrack(value: string | null | undefined, fallback: Track = 'python'): Track {
  return value === 'scratch' || value === 'python' || value === 'roblox' || value === 'unity' || value === 'tosel'
    ? value
    : fallback;
}
